/**
 * Generates simplified SVG land paths for the interactive regions map.
 * Run once (output is committed):  npm run gen:map
 *
 * Source: world-atlas (Natural Earth, public domain) via d3-geo + topojson-client.
 * Two views: whole world and a closer look at Europe (where most classic regions are).
 */
import fs from "node:fs";
import path from "node:path";
import { geoMercator, geoNaturalEarth1, geoPath, geoGraticule, type GeoProjection } from "d3-geo";
import { feature } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";

const require_ = (p: string) => JSON.parse(fs.readFileSync(path.join(process.cwd(), "node_modules", p), "utf8"));

const world110 = require_("world-atlas/land-110m.json") as Topology;
const world50 = require_("world-atlas/land-50m.json") as Topology;
const land110 = feature(world110, world110.objects.land as GeometryCollection);
const land50 = feature(world50, world50.objects.land as GeometryCollection);

/** Round coordinates to whole pixels and drop zero-length segments to keep the file small. */
const round = (s: string) =>
  s
    .replace(/-?\d+\.\d+/g, (n) => Math.round(parseFloat(n)).toString())
    .replace(/L(-?\d+),(-?\d+)(?=L\1,\2)/g, "");

function build(name: string, projection: GeoProjection, land: typeof land110, width: number, height: number) {
  const p = geoPath(projection);
  return {
    name,
    width,
    height,
    land: round(p(land) ?? ""),
    graticule: round(p(geoGraticule().step([20, 20])()) ?? ""),
    scale: projection.scale(),
    translate: projection.translate(),
    rotate: projection.rotate(),
    center: projection.center(),
  };
}

const W = 1000;
const world = build(
  "world",
  geoNaturalEarth1().rotate([-10, 0]).fitExtent([[10, 10], [W - 10, 500]], { type: "Sphere" }),
  land110,
  W,
  510,
);

const europeBox: GeoJSON.Feature = {
  type: "Feature",
  properties: {},
  geometry: { type: "MultiPoint", coordinates: [[-10, 35.5], [30, 35.5], [-10, 55], [30, 55], [45, 44]] },
};
const europe = build(
  "europe",
  geoMercator()
    .fitExtent([[20, 20], [W - 20, 620]], europeBox)
    .clipExtent([[0, 0], [W, 640]]),
  land50,
  W,
  640,
);

const out = `/* Auto-generated by scripts/generate-map.ts – do not edit by hand. Natural Earth data (public domain). */
export const mapViews = ${JSON.stringify({ world, europe })} as const;
`;
fs.writeFileSync(path.join(process.cwd(), "src/components/map/world-paths.ts"), out);
console.log("Map paths written:", (out.length / 1024).toFixed(0), "KB");
